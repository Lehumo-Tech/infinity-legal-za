// LEGAL TRANSLATION (SA 11 official languages)
// ============================================

export interface TranslateInput {
  text: string;
  targetLanguage: string;
  sourceLanguage?: string;
}

export const SA_LANGUAGES: Record<string, string> = {
  en: 'English',
  af: 'Afrikaans',
  zu: 'isiZulu',
  xh: 'isiXhosa',
  st: 'Sesotho',
  tn: 'Setswana',
  ts: 'Xitsonga',
  nso: 'Sepedi',
  ve: 'Tshivenda',
  ss: 'siSwati',
  nr: 'isiNdebele',
};

export async function translateLegal(input: TranslateInput): Promise<LLMChatResult> {
  const targetName = SA_LANGUAGES[input.targetLanguage] || input.targetLanguage;
  const sourceNote = input.sourceLanguage
    ? ` from ${SA_LANGUAGES[input.sourceLanguage] || input.sourceLanguage}`
    : '';

  const messages: LLMMessage[] = [
    { role: 'system', content: TRANSLATE_SYSTEM_PROMPT },
    {
      role: 'user',
      content: `Translate the following legal text${sourceNote} to ${targetName}. Preserve all legal meaning, formatting, and structure:\n\n---\n${input.text}\n---`,
    },
  ];

  return llmChat(messages, {
    cache: true,
    cacheTtl: 2 * 60 * 60 * 1000, // 2 hour cache for translations
    temperature: 0.2, // Very low temperature for translation accuracy
    maxTokens: 4096,
    systemPrompt: TRANSLATE_SYSTEM_PROMPT,
  });
}

