export interface IntakeAnalysisInput {
  name: string;
  caseType: string;
  description: string;
  urgency?: string;
}

export async function analyzeIntake(input: IntakeAnalysisInput): Promise<LLMChatResult> {
  const messages: LLMMessage[] = [
    { role: 'system', content: INTAKE_SYSTEM_PROMPT },
    {
      role: 'user',
      content: `Please analyze the following legal matter:\n\n**Client Name:** ${input.name}\n**Case Type:** ${input.caseType}\n**Urgency:** ${input.urgency || 'Not specified'}\n**Description:** ${input.description}`,
    },
  ];

  return llmChat(messages, {
    cache: false,
    temperature: 0.5, // More deterministic for intake analysis
    maxTokens: 2048,
    systemPrompt: INTAKE_SYSTEM_PROMPT,
  });
}

