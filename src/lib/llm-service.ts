// LEGAL CHAT — Multi-turn conversation
// ============================================

export interface LegalChatOptions extends LLMChatOptions {
  sessionId: string;
}

export async function legalChat(
  userMessage: string,
  options: LegalChatOptions
): Promise<LLMChatResult> {
  const { sessionId, ...llmOptions } = options;

  // Get or create conversation
  const messages = getConversation(sessionId, LEGAL_CHAT_SYSTEM_PROMPT);

  // Add user message
  messages.push({ role: 'user', content: userMessage });

  // Trim if needed
  const trimmed = trimMessages(messages);

  // Call LLM
  const result = await llmChat(trimmed, {
    ...llmOptions,
    cache: false, // Don't cache conversational turns
    systemPrompt: LEGAL_CHAT_SYSTEM_PROMPT,
  });

  // Add assistant response to history
  trimmed.push({ role: 'assistant', content: result.content });

  // Save conversation
  updateConversation(sessionId, trimmed);

  return result;
}

